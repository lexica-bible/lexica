#!/usr/bin/env python3
"""eu_declared_gate2.py - build tests/fixtures/edition_upgrade/declared_deltas.json for gate 2
(edition upgrade). v4 = v3 (DESIGN §9.100 figures, §9.101 G5) + §9.102 G6. Generated, never typed:

  pn_binding        = G5 delta_file: the committed copy of pn8b3c_20261107/pn_binding_delta_after.tsv
                      (160 rows: ADDED 70 / REMOVED 90), sha256-pinned
  gate_b.pins       = 0 / 0 / 0 / 29 (§9.100, from the first gate 2 run)
  gate_b.changed_rows = the 58 rows of the committed copy of pn8b3_20261107/identity_delta.tsv
                      (§9.97, sha256-pinned), shape {book, chapter, verse, position, name},
                      name = the file's label_norm (§9.92 G3)
  gate_b.shape_exceptions = G6: the committed copy of gate2run2_20261107/gate2_run2_dump.tsv
                      (34 rows = 33 'outside the ruled classes' + Gen 38:1 'not a people-word',
                      all ACCEPT under §9.100), sha256-pinned; every row must be one of the 58
  everything else   = v2 unchanged (words / verses counts, abp_surface + pn_greek_identity
                      key moves, tipnr_entities identical)

Checks every input file's sha256 and row counts first; any mismatch = exit 2, nothing written.
Usage: python scripts/eu_declared_gate2.py [<out.json>]   (default: the committed fixture path)
"""
import ast
import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIX = "tests/fixtures/edition_upgrade"
DELTA = FIX + "/pn_binding_delta_20261107.tsv"
DELTA_SHA = "f26fb503ad160841e25052f083c26ac828eb64e569041cdb6d8689c9fc62072b"
IDENT = FIX + "/identity_delta_20261107.tsv"
IDENT_SHA = "62a99ffe59658f46b9e8a5e385d643b7a147870f38f83136b541d52c5950acca"
EXC = FIX + "/gate2_shape_exceptions_20261107.tsv"
EXC_SHA = "b43e0a12bcaa4ae6a3ce67f175420ae06df488af3dc6fae6ed66b6f7e1dfba9f"
OUT = FIX + "/declared_deltas.json"
PINS = {"pinned ruled loss": 0, "glued cure (blanked)": 0,
        "glued cure (replaced)": 0, "glued kept as-is": 29}
OUTSIDE = "outside the ruled classes"
PEOPLE = "is not a people-word"


def stop(msg):
    print("EU DECLARED GATE2: STOP - " + msg)
    sys.exit(2)


def read_checked(rel, sha, rows, header_lines=1):
    with open(os.path.join(ROOT, rel), "rb") as fh:
        raw = fh.read()
    got = hashlib.sha256(raw).hexdigest()
    if got != sha:
        stop("%s sha256 %s != pinned %s" % (rel, got, sha))
    lines = raw.decode("utf-8").splitlines()
    if len(lines) - header_lines != rows:
        stop("%s has %d rows, expected %d" % (rel, len(lines) - header_lines, rows))
    return lines


def changed_rows():
    lines = read_checked(IDENT, IDENT_SHA, 58)
    hdr = lines[0].split("\t")
    if hdr[:7] != ["kind", "verse_id", "ref", "position", "english_built", "strongs_base_built", "label_norm"]:
        stop("%s: unexpected header %r" % (IDENT, lines[0]))
    out = []
    for ln in lines[1:]:
        p = ln.split("\t")
        book, cv = p[2].split(" ")
        ch, vs = cv.split(":")
        out.append({"book": book, "chapter": int(ch), "verse": int(vs),
                    "position": int(p[3]), "name": ast.literal_eval(p[6])})
    keys = {(d["book"], d["chapter"], d["verse"], d["position"]) for d in out}
    if len(keys) != 58:
        stop("identity delta keys are not 58 distinct rows")
    return out


def check_exceptions(rows):
    """The G6 exceptions file: 34 problem rows (33 + 1), each one of the 58 changed rows."""
    lines = read_checked(EXC, EXC_SHA, 34, header_lines=2)
    if not lines[0].startswith("#") or not lines[1].startswith("ref\tpos\t"):
        stop("%s: not a gate --dump file" % EXC)
    in58 = {(d["book"], d["chapter"], d["verse"], d["position"]) for d in rows}
    seen, n_out, n_ppl = set(), 0, 0
    for ln in lines[2:]:
        p = ln.split("\t")
        if len(p) != 9:
            stop("%s: a row has %d columns" % (EXC, len(p)))
        book, cv = p[0].rsplit(" ", 1)
        ch, vs = cv.split(":")
        k = (book, int(ch), int(vs), int(p[1]))
        if k in seen:
            stop("%s: %r twice" % (EXC, k))
        if k not in in58:
            stop("%s: %r is not one of the 58 changed rows" % (EXC, k))
        seen.add(k)
        n_out += OUTSIDE in p[8]
        n_ppl += PEOPLE in p[8]
    if (n_out, n_ppl) != (33, 1):
        stop("%s: notes %d outside / %d people-word, expected 33 / 1" % (EXC, n_out, n_ppl))


def build():
    read_checked(DELTA, DELTA_SHA, 160)
    rows = changed_rows()
    check_exceptions(rows)
    return {
        "_what": ("gate_greek_header.py --declared, edition upgrade gate 2, v4 - GENERATED by "
                  "scripts/eu_declared_gate2.py, never hand-edited (DESIGN 9.100 figures, 9.101 G5, "
                  "9.102 G6). pn_binding is declared by the sha-pinned delta file (the 160 rows of "
                  "pn8b3c_20261107/pn_binding_delta_after.tsv: ADDED 70 / REMOVED 90). gate_b pins are "
                  "the first gate 2 run's figures (0/0/0/29), changed_rows are the 58 rows of "
                  "pn8b3_20261107/identity_delta.tsv (9.97), name = its label_norm, and shape_exceptions "
                  "is the sha-pinned dump of GATE2-RUN2 (34 rows, all ACCEPT under 9.100). Everything "
                  "else is v2: the 6 + 15 key moves (9.94), words 626,309 / verses 31,237, "
                  "tipnr_entities identical. The 3 Michaiah rows stay out (9.58). pn_binding.book is a NUMBER."),
        "lane": "edition upgrade 2026-11 (bible_edupg_test_20261101.db -> bible_edupg_test_built_20261102.db)",
        "declared_by": "ruling chat 2026-11-07 (DESIGN 9.100, 9.101, 9.102)",
        "receipt": ("gate2run1_20261107 (out + dump), g2read_20261107.log, g2memb_20261107.log, "
                    "gate2dump_20261107_r2.log, gate2run2_20261107.log"),
        "words": {"scratch_count": 626309},
        "verses": {"scratch_count": 31237},
        "abp_surface": {"key_moves_file": FIX + "/abp_surface_key_moves_20261106.tsv"},
        "tipnr_entities": {"identical": True},
        "pn_binding": {"delta_file": DELTA, "sha256": DELTA_SHA},
        "pn_greek_identity": {
            "keys_only_in_live": 6, "keys_only_in_scratch": 6,
            "key_moves_file": FIX + "/pn_greek_identity_key_moves_20261106.tsv",
            "note": ("Sheshach rows (9.69: Jer 51:41 pos 1, Jer 25:26 pos 25) are declared UNCHANGED "
                     "(9.92 as amended; 9.100: unchanged, nothing to declare)."),
        },
        "gate_b": {"pins": PINS, "changed_rows": rows,
                   "shape_exceptions": {"file": EXC, "sha256": EXC_SHA}},
    }


def render(d):
    return json.dumps(d, ensure_ascii=False, indent=1) + "\n"


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, OUT)
    text = render(build())
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("EU DECLARED GATE2: wrote %s (v4) - pn_binding delta_file 160 rows, gate_b pins %s, "
          "changed_rows 58, shape_exceptions 34" % (out, PINS))


if __name__ == "__main__":
    main()
